import {Router} from 'express';
import {login,me} from '../controllers/authController.js';
import {protect,allowRoles} from '../middleware/auth.js';
import * as patients from '../controllers/patientController.js';
import * as master from '../controllers/masterController.js';
import * as appointments from '../controllers/appointmentController.js';
import * as queue from '../controllers/queueController.js';
import {summary} from '../controllers/dashboardController.js';
import {asyncHandler} from '../utils/asyncHandler.js';
const r=Router();
r.post('/auth/login',asyncHandler(login));r.get('/auth/me',protect,asyncHandler(me));
r.use(protect);
r.get('/dashboard/summary',asyncHandler(summary));
r.get('/patients',asyncHandler(patients.listPatients));r.post('/patients',allowRoles('super_admin','hospital_admin','receptionist','nurse'),asyncHandler(patients.createPatient));
r.get('/patients/:id',asyncHandler(patients.getPatient));r.patch('/patients/:id',allowRoles('super_admin','hospital_admin','receptionist'),asyncHandler(patients.updatePatient));
r.get('/departments',asyncHandler(master.departments));r.post('/departments',allowRoles('super_admin','hospital_admin'),asyncHandler(master.createDepartment));
r.get('/doctors',asyncHandler(master.doctors));r.post('/doctors',allowRoles('super_admin','hospital_admin'),asyncHandler(master.createDoctor));
r.get('/appointments',asyncHandler(appointments.listAppointments));r.post('/appointments',allowRoles('super_admin','hospital_admin','receptionist'),asyncHandler(appointments.createAppointment));
r.patch('/appointments/:id/status',allowRoles('super_admin','hospital_admin','receptionist','doctor'),asyncHandler(appointments.updateAppointmentStatus));
r.get('/queue/live',asyncHandler(queue.liveQueue));r.post('/queue/check-in',allowRoles('super_admin','hospital_admin','receptionist','nurse'),asyncHandler(queue.checkIn));
r.post('/queue/:tokenId/:action',allowRoles('super_admin','hospital_admin','receptionist','doctor','nurse'),asyncHandler(queue.queueAction));
export default r;
